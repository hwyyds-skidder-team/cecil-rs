"""Deterministic malformed PE corpus and dnlib 4.5.0 reader comparison.

Build the two probes first; pass their binaries with --rust and --dnlib.
All generated bytes and reports stay under --output. No input is overwritten.
"""
import argparse
import hashlib
import json
import struct
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def corpus(output):
    cases = []
    def add(name, data):
        path = output / "corpus" / (name + ".bin")
        path.write_bytes(data)
        cases.append({"name": name, "path": str(path.resolve()), "bytes": len(data),
                      "sha256": hashlib.sha256(data).hexdigest()})
    (output / "corpus").mkdir(parents=True, exist_ok=True)
    for fixture in sorted((ROOT / "fixtures").iterdir()):
        if fixture.suffix.lower() in (".dll", ".exe", ".netmodule", ".winmd"):
            add("fixture-" + fixture.name, fixture.read_bytes())
    for fixture_name in ("hello.exe", "MixedNativeCLI.exe", "cecil.dll"):
        raw = (ROOT / "fixtures" / fixture_name).read_bytes()
        for size in (0, 1, 63, 64, 128, 256, 511, len(raw) // 2, len(raw) - 1):
            add(fixture_name + "-truncated-" + str(size), raw[:size])
        # Mutate header/section metadata and regular samples throughout the
        # image. Reproducible positions/values prevent corpus drift.
        positions = sorted(set(range(0, min(1024, len(raw)), 17)) | {
            i * (len(raw) - 4) // 128 for i in range(129)})
        for pos in positions:
            if pos + 4 <= len(raw):
                for value in (0, 0xFFFFFFFF):
                    data = bytearray(raw)
                    struct.pack_into("<I", data, pos, value)
                    add(f"{fixture_name}-{pos:08x}-{value:08x}", data)
    return cases


def probe(command, cases):
    result = subprocess.run(command, input="".join(c["path"] + "\n" for c in cases),
                            text=True, encoding="utf-8", errors="replace", capture_output=True, timeout=180)
    lines = result.stdout.splitlines()
    if result.returncode != 0 or len(lines) != len(cases):
        raise RuntimeError(f"probe failed ({result.returncode}, {len(lines)}/{len(cases)}): {result.stderr[-3000:]}")
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rust", type=Path, required=True)
    parser.add_argument("--dnlib", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    cases = corpus(args.output)
    rust = probe([str(args.rust.resolve())], cases)
    dnlib = probe(["dotnet", str(args.dnlib.resolve())], cases)
    for case, ours, reference in zip(cases, rust, dnlib):
        case["cecil"] = ours
        case["dnlib"] = reference
    summary = {"cases": len(cases), "cecil_panics": sum(v == "panic" for v in rust),
               "cecil_accepted": sum(v.startswith("ok\t") for v in rust),
               "dnlib_accepted": sum(v.startswith("ok\t") for v in dnlib),
               "dnlib_limits": sum(v.startswith("limit\t") for v in dnlib),
               "dnlib_only": sum(d.startswith("ok\t") and not r.startswith("ok\t") for r, d in zip(rust, dnlib)),
               "cecil_only": sum(r.startswith("ok\t") and not d.startswith("ok\t") for r, d in zip(rust, dnlib))}
    (args.output / "comparison.json").write_text(json.dumps({"summary": summary, "cases": cases}, indent=2), encoding="utf-8")
    print(json.dumps(summary))
    if summary["cecil_panics"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
